        assert_eq!(
            call.args,
            &[
                JitHelperArgKind::VmContext,
                JitHelperArgKind::U64,
                JitHelperArgKind::U64
            ]
        );
        assert_eq!(call.returns, JitHelperReturnKind::Status);
